"use strict";
const assert = require("node:assert/strict");
const { evaluateDemo } = require("./app.js");
const base = {task_id:"T-1",target_identifier:"SYN-1",primary_metric:10,secondary_metric:5,status_descriptor:"NOMINAL",is_critical_flag:false};
let result = evaluateDemo(base);
assert.equal(result.overall_urgency, "ROUTINE");
assert.equal(result.total_alerts, 0);
assert.equal(result.signed_audit_trail, false);
result = evaluateDemo({...base,primary_metric:26});
assert.equal(result.overall_urgency, "ELEVATED_RISK");
assert.equal(result.total_alerts, 1);
result = evaluateDemo({...base,secondary_metric:13,status_descriptor:"DISCORDANT"});
assert.equal(result.total_alerts, 2);
result = evaluateDemo({...base,is_critical_flag:true});
assert.equal(result.overall_urgency,"CRITICAL_STAT_PANIC");
assert.equal(result.critical_alerts_count, 1);
assert.throws(() => evaluateDemo({...base,primary_metric:Infinity}),/finite/);
assert.throws(() => evaluateDemo({...base,secondary_metric:NaN}),/finite/);
console.log("Browser demo rule tests passed");
